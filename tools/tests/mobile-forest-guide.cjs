const assert = require('node:assert/strict');
const data = require('../../data/forest-guide.json');
const { GuideVisit } = require('../../js/forest-mobile-guide.js');
const visit = new GuideVisit(data);
assert.equal(visit.choose(0, {ready:false}), null);
assert.equal(visit.choose(0, {moving:true}), null);
visit.record(visit.choose(0), 0);
assert.equal(visit.choose(data.cooldownMs-1), null);
const idle = visit.choose(data.cooldownMs);
assert.equal(idle.trigger, 'idle');
visit.record(idle, data.cooldownMs);
assert.notEqual(visit.choose(86400000)?.id, idle.id, 'recent idle line must not repeat');
const alternate = new GuideVisit(data, 0, idle.id);
alternate.record(alternate.choose(0), 0);
assert.notEqual(alternate.choose(120000).id, idle.id);
for (let i = 0; i < 15; i++) visit.move(240000 + i * 1000);
assert.equal(visit.choose(255000, {moving:true}).trigger, 'walking');
const near = visit.choose(255000, {areas:['observatory']});
assert.equal(near.id, 'guide_observatory');
visit.record(near, 255000);
visit.pause(400000);
assert.equal(visit.choose(400000+data.cooldownMs-1), null, 'resume restarts quiet cooldown');
visit.move(520000);
const next = visit.choose(565000, {areas:['observatory']});
assert.notEqual(next.id, near.id);
visit.record(next, 565000);
assert.equal(visit.snapshot().count, 4);
visit.move(700000);
visit.count=data.maxPerVisit;
assert.equal(visit.choose(700000, {areas:['shrine']}), null, 'configured visit limit');
assert.equal(new Set(visit.snapshot().used).size, 4);
const other = structuredClone(data);
other.guideCharacterId = 'future-guide';
other.dialogue = [{id:'future-entry', guideCharacterId:'future-guide', trigger:'entry', priority:1, text:'Hello'}];
assert.equal(new GuideVisit(other).choose(0).id, 'future-entry');
assert.deepEqual(require('../../docs/data/forest-guide.json'), data);
console.log('Guide policy: cooldown, idle limit, alternate hint, walking, proximity, pause, visit limit and character selection passed.');
